function normalizeName(value: string) {
  return value
    .normalize('NFD')
    .replaceAll(/\p{Diacritic}/gu, '')
    .toLocaleLowerCase('pt-BR')
    .replaceAll(/[^a-z0-9]+/g, ' ')
    .trim()
}

function includesPhrase(value: string, phrase: string) {
  return ` ${value} `.includes(` ${phrase} `)
}

export function getProductFacets(source: string, name: string) {
  const features: ProductFeature[] = []
  const themes: ProductTheme[] = []
  const normalizedName = normalizeName(name)

  if (largeBeadSources.has(source)) features.push('large-beads')
  if (smallBeadSources.has(source)) features.push('small-beads')
  if (bandanaSources.has(source)) features.push('bandana')

  for (const option of productThemeOptions) {
    if (
      themeKeywords[option.value].some((keyword) =>
        includesPhrase(normalizedName, keyword),
      )
    ) {
      themes.push(option.value)
    }
  }

  if (devotionalSources.has(source) && !themes.includes('devotional')) {
    themes.push('devotional')
  }

  return { features, themes }
}
